            <p>
                For functional used generators, valuation is determined by engine make and model (e.g., Cat, Cummins, Perkins), verified running hours from the electronic control module (ECM), overall mechanical condition, presence of soundproof canopies, and secondary market demand. For scrap generators, valuation is calculated strictly on certified scrap metal weight—specifically heavy cast-iron engine blocks, steel enclosures, and high-purity copper windings from alternators.
            </p>

            <h3>Can you dismantle and remove multiple portacabins from our site simultaneously?</h3>
            <p>
                Yes. Rental Power UAE has the heavy logistics capacity to clear entire 50-cabin site compounds in a matter of days. We deploy tandem mobile cranes, cutting crews, and a continuous convoy of low-bed trailers to ensure full site demobilization before your land lease or project permit expires.
            </p>

            <h3>What testing do you perform on a refurbished generator before we take delivery?</h3>
            <p>
                Every refurbished generator undergoes our certified 50-point technical audit. This culminates in a continuous 4-hour resistive load bank test at 100% rated capacity and 1 hour at 110% overload. Alternators undergo 1000V DC Megger insulation resistance testing, and engine cylinders are inspected with digital borescopes. You receive a certified load bank test certificate and comprehensive workshop warranty.
            </p>

