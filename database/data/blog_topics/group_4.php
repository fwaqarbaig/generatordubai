<h3>1. Engine Crankcase Blow-By and Compression Check</h3>
<p>With the diesel engine warm and running under partial load, safely open the oil filler cap. Excessive pulsing fumes or oil droplet spray venting from the filler neck (known as <strong>crankcase blow-by</strong>) indicates worn piston rings, glazed cylinder liners, or valve guide wear. A healthy diesel engine should produce minimal clear vapor.</p>

